const assert=require('assert/strict');
const {device,store,service,clone}=require('./account_save_test.js');
const a='standard_catcheurs_angelo_folena',b='rare_catcheurs_rayen_gurzil';
(async()=>{
  const uid='guided-owner';
  const cloud={uid,level:23,careerXpWins:{career_24_Final:true},playerState:{credits:350,collection:{[a]:1,[b]:1},careerUnlocked:3,starterGranted:true,welcomeClaimed:true,boosterTickets:{premium:0}},deckState:{decks:[{id:'shared',name:'Mobile',cards:[b]}],selectedId:'shared'}};
  store.set(uid,clone(cloud));
  const phone=device(uid,[],{mobile:true});
  await assert.rejects(phone.login(uid),error=>error.code==='allstar/save-setup-required');
  assert.equal(phone.session().blocked,true);assert.equal(phone.session().setup,true);
  assert.equal(phone.session().cloudSourceUsable,false,'Incoherent career cannot be confirmed as correct');
  await assert.rejects(phone.pushCloudSaveNow(),error=>error.code==='allstar/save-protection');
  phone.setupSaveLater();
  assert.equal(phone.session(),null);assert.deepEqual(store.get(uid),cloud,'Later never writes a new save or a source confirmation');
  await assert.rejects(phone.login(uid),error=>error.code==='allstar/save-setup-required');
  const pc=device(uid,[],{desktop:true});
  const full={credits:50,collection:{[a]:8},careerUnlocked:24,starterGranted:true,welcomeClaimed:true,boosterTickets:{premium:1},profileProgress:{uid,level:23}};
  const pcDecks={decks:[{id:'shared',name:'PC',cards:[a]}],selectedId:'shared'};
  const raw=JSON.stringify(full);
  pc.storage.setItem('allstarsPlayerV1',raw);pc.storage.setItem('allstarsDecks',JSON.stringify(pcDecks));
  await assert.rejects(pc.login(uid),error=>error.code==='allstar/save-protection');
  assert.deepEqual(pc.session().pcSource.playerState,full);
  const exported=pc.buildAccountTransferExport();
  assert.equal(exported.playerState.credits,50,'Protected PC copy can be exported directly without loading the partial account');
  await pc.preparePcAccountLink();
  const prepared=clone(store.get(uid));
  assert.deepEqual(prepared.playerState,cloud.playerState,'Preparation does not replace active account progression');
  assert.equal(prepared.pendingPcTransfer.bundle.playerState.credits,50);
  assert.equal(prepared.pcSaveBackup.playerState.collection[a],8);
  assert.equal(pc.storage.getItem('allstarsPlayerV1'),raw);
  const pendingHash=prepared.pendingPcTransfer.hash;
  store.get(uid).pendingPcTransfer.bundle.playerState.credits=99999;
  await phone.receivePreparedPcSave();
  assert.match(phone.transferUi.accountSaveSetupStatus.textContent,/vérifiée/);
  assert.equal(phone.pendingTransfer(),null,'Altered prepared data never becomes a preview');
  store.set(uid,clone(prepared));
  await phone.receivePreparedPcSave();
  assert.equal(phone.pendingTransfer().linkedPc,true);
  assert.deepEqual(store.get(uid).playerState,cloud.playerState,'Receiving and preview remain read-only');
  assert.match(phone.transferUi.accountTransferReview.textContent,/solde de crédits et les tickets/);
  await phone.confirmAccountTransfer();
  const linked=store.get(uid);
  assert.equal(linked.playerState.credits,50,'PC wallet selected explicitly, not added to phone wallet');
  assert.equal(linked.playerState.boosterTickets.premium,1);
  assert.equal(linked.collection[a],8);assert.equal(linked.collection[b],1,'Phone-only card is retained');
  assert.equal(linked.playerState.careerUnlocked,24);
  assert.equal(linked.deckState.decks.length,2,'Different decks with the same ID are both preserved');
  assert.equal(linked.saveLinkVerified.source,'pc-import');assert.equal(linked.pendingPcTransfer,null);
  assert.equal(linked.accountRecoveryReceipts[pendingHash],true);
  assert.equal(linked.pcSaveBackup.playerState.credits,50);
  assert.equal(linked.cloudSaveHistory.verifiedSource.playerState.collection[a],8);
  assert.equal(linked.cloudSaveHistory.verifiedSource.playerState.collection[b],1,'First confirmed merged source remains a durable recovery point');
  assert.notEqual(phone.session()?.blocked,true);
  await phone.login(uid);await pc.login(uid);
  assert.equal(pc.session().blocked,undefined);
  assert.equal(JSON.parse(pc.storage.getItem(pc.scope().player)).credits,50);
  const next=clone(linked.playerState);next.credits=100;
  phone.setExportState(next,linked.deckState);phone.queueCloudSave();await phone.pushCloudSaveNow();
  await pc.login(uid);
  assert.equal(JSON.parse(pc.storage.getItem(pc.scope().player)).credits,100,'Normal phone-to-PC sync requires no further handoff');
  await pc.preparePcAccountLink();
  assert.equal(store.get(uid).pendingPcTransfer,null,'A validated link cannot prepare stale PC sources again');

  const correctUid='already-correct';
  const correct={uid:correctUid,level:4,playerState:{credits:200,collection:{[a]:3},careerUnlocked:2,starterGranted:true,welcomeClaimed:true},deckState:{decks:[{id:'ready',cards:[a]}]}};
  store.set(correctUid,clone(correct));
  const ready=device(correctUid,[],{mobile:true});
  await assert.rejects(ready.login(correctUid),error=>error.code==='allstar/save-setup-required');
  assert.equal(ready.session().cloudSourceUsable,true);
  await ready.confirmCurrentSaveSource();
  assert.equal(store.get(correctUid).saveLinkVerified,undefined,'No confirmation without explicit checked acknowledgement');
  ready.transferUi.accountSaveSetupAcknowledged.checked=true;
  await ready.confirmCurrentSaveSource();
  assert.equal(store.get(correctUid).saveLinkVerified.source,'player-confirmed');
  assert.equal(store.get(correctUid).playerState.credits,200);
  assert.equal(store.get(correctUid).cloudSaveHistory.verifiedSource.playerState.credits,200);
  await ready.login(correctUid);
  assert.notEqual(ready.session()?.blocked,true,'Confirmed existing progress is not questioned on every login');
  const newbie=device('new-account',[],{mobile:true});
  store.set('new-account',{uid:'new-account',level:1,collection:{}});
  await newbie.login('new-account',{newAccount:true});
  assert.equal(newbie.session().sourceReady,'new-mobile-account','Genuine phone account registration skips old-PC guide');
  newbie.setExportState({credits:1000,collection:{[a]:1},careerUnlocked:0,starterGranted:true,welcomeClaimed:true},{decks:[{id:'starter',cards:[a]}]});
  await newbie.pushCloudSaveNow();
  assert.equal(store.get('new-account').saveLinkVerified.source,'new-mobile-account');
  await newbie.login('new-account');
  assert.notEqual(newbie.session()?.blocked,true);
  const newPc=device('new-pc',[],{desktop:true});
  store.set('new-pc',{uid:'new-pc',level:1,collection:{}});
  await newPc.login('new-pc',{newAccount:true});
  newPc.setExportState({credits:1000,collection:{[a]:1},careerUnlocked:0,starterGranted:true,welcomeClaimed:true},{decks:[{id:'starter',cards:[a]}]});
  await newPc.pushCloudSaveNow();
  assert.equal(store.get('new-pc').saveLinkVerified.source,'new-pc-account');
  const newPcPhone=device('new-pc',[],{mobile:true});
  await assert.rejects(newPcPhone.login('new-pc'),error=>error.code==='allstar/save-setup-required');
  assert.equal(newPcPhone.session().cloudSourceUsable,true,'A new PC-origin account still gets the first-phone verification');
  const stale=device('stale-preparation',[],{desktop:true});
  const staleCloud=clone(correct);staleCloud.uid='stale-preparation';
  store.set('stale-preparation',staleCloud);
  await stale.login('stale-preparation');stale.setExportState(staleCloud.playerState,staleCloud.deckState);
  await stale.preparePcAccountLink();
  assert(store.get('stale-preparation').pendingPcTransfer);
  const preparedBackup=clone(store.get('stale-preparation').pcSaveBackup);
  const newer=clone(staleCloud.playerState);newer.credits++;
  stale.setExportState(newer,staleCloud.deckState);stale.queueCloudSave();await stale.pushCloudSaveNow();
  assert.equal(store.get('stale-preparation').pendingPcTransfer,null,'Meaningful play after preparation invalidates the stale copy');
  assert.deepEqual(store.get('stale-preparation').pcSaveBackup,preparedBackup,'First PC backup survives invalidation');

  const brokenUid='missing-local-decks',broken=device(brokenUid,[],{desktop:true});
  store.set(brokenUid,{...clone(correct),uid:brokenUid});
  broken.storage.setItem(`allstarsPlayerV1:account:${brokenUid}`,JSON.stringify({...clone(full),profileProgress:{uid:brokenUid}}));
  await assert.rejects(broken.login(brokenUid),error=>error.code==='allstar/save-protection');
  assert.equal(broken.session().pcSource,null,'Missing local decks cannot silently become an empty exported deck list');
  assert.throws(()=>broken.buildAccountTransferExport(),/vérification/);

  const foreign=device('foreign',[],{mobile:true});store.set('foreign',clone(correct));
  await assert.rejects(foreign.login('foreign'),error=>error.code==='allstar/save-setup-required');
  const beforeForeign=clone(store.get('foreign'));
  await foreign.reviewAccountTransfer({size:1000,text:async()=>JSON.stringify(prepared.pendingPcTransfer.bundle)});
  assert.match(foreign.transferUi.accountTransferReview.textContent,/compte connecté/);
  assert.deepEqual(store.get('foreign'),beforeForeign);
  assert.equal(ready.normalize(prepared).pendingPcTransfer,undefined);
  assert.equal(ready.normalize(prepared).pcSaveBackup,undefined);
  console.log('Guided first mobile login: Later read-only, protected PC preparation/export, verified fileless retrieval, merge without card/deck loss, explicit PC wallet, one-time link and normal sync verified.');
})().catch(error=>{console.error(error);process.exitCode=1});
